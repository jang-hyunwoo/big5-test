if submitted:
    # 점수 저장소 초기화
    scores = {"O": 0, "C": 0, "E": 0, "A": 0, "N": 0}

    for q, ans in user_answers:
        # 역채점 계산
        if q["역채점"] == True:
            final_score = 6 - ans
        else:
            final_score = ans

        # 점수 더하기
        scores[q["유형"]] += final_score

